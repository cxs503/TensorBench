#!/usr/bin/env python3
"""Insert the board-audit verdict for m14899 (KPI-BENCH-10) into tensor_maturity_verdicts.

Reads docs/audit_m14899/verdict_evidence.json (the evidence bundle), renders
docs/audit_m14899/verdict.sql with proper SQL escaping, and applies it unless
--dry-run is given.  Idempotent via ON CONFLICT (repo, scope, verdict_by).
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUNDLE = os.path.join(HERE, "verdict_evidence.json")
SQL_OUT = os.path.join(HERE, "verdict.sql")
DB = ["psql", "-d", "tensorplatform", "-U", "ship", "-v", "ON_ERROR_STOP=1"]


def literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render(bundle: dict) -> str:
    payload = json.dumps(bundle["evidence"], ensure_ascii=False, sort_keys=True)
    return (
        "-- Generated by docs/audit_m14899/insert_verdict.py from verdict_evidence.json.\n"
        "-- Board audit verdict for m14899 (KPI-BENCH-10), delivered by mission m14957.\n"
        "-- Evidence keys required by the gate: impl_files / entry / run_artifacts / tests /\n"
        "-- integration_callers / benchmark / repro_cmd / external_anchor.\n"
        "INSERT INTO tensor_maturity_verdicts (repo, scope, mission_id, level, evidence, verdict_by) VALUES (\n"
        f"{literal(bundle['repo'])},\n{literal(bundle['scope'])},\n{bundle['mission_id']},\n"
        f"{bundle['level']},\n{literal(payload)}::jsonb,\n{literal(bundle['verdict_by'])}\n)\n"
        "ON CONFLICT (repo, scope, verdict_by) DO UPDATE\n"
        "  SET level = EXCLUDED.level, evidence = EXCLUDED.evidence, mission_id = EXCLUDED.mission_id;\n"
    )


def main() -> int:
    bundle = json.load(open(BUNDLE, encoding="utf-8"))
    sql = render(bundle)
    with open(SQL_OUT, "w", encoding="utf-8") as fh:
        fh.write(sql)
    print(f"rendered {SQL_OUT} ({len(sql)} bytes), level={bundle['level']} scope={bundle['scope']!r}")
    if "--dry-run" in sys.argv[1:]:
        return 0
    res = subprocess.run(DB + ["-f", SQL_OUT], capture_output=True, text=True)
    print(res.stdout.strip() or res.stderr.strip())
    if res.returncode != 0:
        return 2
    read = subprocess.run(
        DB + ["-At", "-c",
              "select id, repo, scope, mission_id, level, verdict_by, gate_state from tensor_maturity_verdicts "
              "where verdict_by='board-audit' and scope like 'm14899%'"],
        capture_output=True, text=True)
    print("readback:", read.stdout.strip() or read.stderr.strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())