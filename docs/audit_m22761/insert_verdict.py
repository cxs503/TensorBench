#!/usr/bin/env python3
"""Insert the PV pilot verdict into tensor_maturity_verdicts (mission m22761, action ②).

The m22510 review mission produced a passing six-check receipt but never wrote the
verdict row, so the PV line's maturity level stayed absent from the ledger. This
script renders ``verdict.sql`` from ``verdict_evidence.json`` (proper SQL escaping)
and applies it unless ``--dry-run`` is passed. Idempotent via
ON CONFLICT (repo, scope, verdict_by).

The `level` is not copied from the receipt (the receipt has no `level` field); it is
derived by applying the platform maturity rubric to the receipt's own evidence and
the derivation is recorded in evidence.level_reason.

Run: python3 docs/audit_m22761/insert_verdict.py [--dry-run]
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUNDLE = os.path.join(HERE, "verdict_evidence.json")
SQL_OUT = os.path.join(HERE, "verdict.sql")
DB = ["psql", "-d", "tensorplatform", "-U", "ship", "-v", "ON_ERROR_STOP=1"]


def literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render(bundle: dict) -> str:
    payload = json.dumps(bundle["evidence"], ensure_ascii=False, sort_keys=True)
    return (
        "-- Generated by docs/audit_m22761/insert_verdict.py from verdict_evidence.json.\n"
        "-- PV (Physics Dataset Validator) pilot verdict, mission m22061, delivered by m22761.\n"
        "-- Backfills the verdict row the m22510 review mission left unwritten.\n"
        "INSERT INTO tensor_maturity_verdicts (repo, scope, mission_id, level, evidence, verdict_by) VALUES (\n"
        f"{literal(bundle['repo'])},\n{literal(bundle['scope'])},\n{bundle['mission_id']},\n"
        f"{bundle['level']},\n{literal(payload)}::jsonb,\n{literal(bundle['verdict_by'])}\n)\n"
        "ON CONFLICT (repo, scope, verdict_by) DO UPDATE\n"
        "  SET level = EXCLUDED.level, evidence = EXCLUDED.evidence, mission_id = EXCLUDED.mission_id;\n"
    )


def readback() -> str:
    query = (
        "select id, repo, scope, mission_id, level, verdict_by, gate_state "
        "from tensor_maturity_verdicts where repo='TensorData' and mission_id=22061"
    )
    res = subprocess.run(DB + ["-At", "-c", query], capture_output=True, text=True)
    return res.stdout.strip() or res.stderr.strip()


def main(argv: list[str]) -> int:
    bundle = json.load(open(BUNDLE, encoding="utf-8"))
    sql = render(bundle)
    with open(SQL_OUT, "w", encoding="utf-8") as fh:
        fh.write(sql)
    print(
        f"rendered {SQL_OUT} ({len(sql)} bytes), level={bundle['level']} "
        f"scope={bundle['scope']!r}"
    )
    if "--dry-run" in argv[1:]:
        return 0
    res = subprocess.run(DB + ["-f", SQL_OUT], capture_output=True, text=True)
    print(res.stdout.strip() or res.stderr.strip())
    if res.returncode != 0:
        return 2
    print("readback:", readback())
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))